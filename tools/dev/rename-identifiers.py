def is_kept(path):
    name = str(path)
    return any(name == kept.rstrip("/") or name.startswith(kept) if not kept.startswith("/") else kept in "/" + name
               for kept in KEEP_PATHS)


def rewrite_source(text, path, language):
    out = []
    for kind, chunk in lex(text, language):
        masked, spans = mask(chunk)
        if kind == "code":
            masked = map_identifiers(masked, path, "code")
        elif kind == "comment":
            masked = map_prose(masked, path)
        else:
            masked = map_string(masked, path)
        out.append(unmask(masked, spans))
    return "".join(out)


def rewrite_text(text, path):
    masked, spans = mask(text)
    masked = map_prose(masked, path, emblem_words=path.suffix == ".md")
    return unmask(masked, spans)


def rewrite(path):
    text = path.read_text()
    language = SOURCE_LANGUAGES.get(path.suffix)
    new = rewrite_source(text, path, language) if language else rewrite_text(text, path)
    return new


def new_path(path):
    if str(path).startswith(KEPT_LOCATIONS):
        return path
    parts = []
    for part in path.parts:
        if part in KEPT_FOLDERS or re.fullmatch(r"crest_[a-z_]+\.h|CrestChromiumHost\.h|Crest-Native-Host", part) \
                or re.match(r"CrestChromiumUI(?:Product)?\b", part):
            parts.append(part)
            continue
        if part == "Crest" and "BrowserSpaceBranding" in str(path):
            parts.append("Emblem")
            continue
        renamed = part
        for old, new in LOWER_SUBSTRINGS.items():
            renamed = renamed.replace(old, new)
        renamed = IDENTIFIER.sub(lambda match: match.group(0) if match.group(0) in ("crest", "crests")
                                 else map_token(match.group(0), path, "path"), renamed)
        parts.append(renamed)
    return Path(*parts)


