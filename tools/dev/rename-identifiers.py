def engine_names():
    """Names the engine's own sources use in code, which documents and
    comments cite as the engine spells them."""
    root = ROOT / "CrestEngines/Chromium"
    files = [path for path in (root / "Overlay").rglob("*") if path.is_file()]
    files += sorted((root / "Patches").glob("*.patch")) + [HOST_HEADER]
    names = set()
    for path in files:
        for kind, chunk in lex(path.read_text(errors="ignore"), "c"):
            if kind == "code":
                names.update(token for token in IDENTIFIER.findall(chunk) if "Crest" in token and token != "Crest")
    return names


# Prefixes of those names, as comments cite them ("the CREST_ macros").
ABI_PREFIXES = {name[:index + 1] for name in ABI_NAMES for index, character in enumerate(name) if character == "_"}


def product_token(token):
    """`token` with each camel-case `Crest` segment renamed."""
    return re.sub(r"Crest(?=[A-Z0-9_]|s?$|s[A-Z])", "Ode", token)


def map_token(token, path, kind):
    """The new spelling of one identifier-shaped token."""
    if token in ABI_NAMES or token in ABI_PREFIXES or not re.search(r"crest", token, re.IGNORECASE):
        return token
    if kind in ("comment", "prose") and token in ENGINE_NAMES:
        return token
    if kind == "template" and "Crest" not in token:
        # Emitted C names and contract labels are part of the wire.
        return token
    if token in EMBLEM_TOKENS:
        return EMBLEM_TOKENS[token]
    if token in PRODUCT_LOWER_TOKENS:
        return PRODUCT_LOWER_TOKENS[token]
    if token.startswith("CREST_"):
        return "ODE_" + token[len("CREST_"):]
    if token in ("crest", "crests"):
        if SOURCE_LANGUAGES.get(path.suffix) == "c" and kind == "code":
            return token  # the C++ namespace of the engine contract header
        if kind == "comment" or kind == "prose":
            return "emblem" + token[len("crest"):]
        if str(path).endswith(CORE_VARIABLE_FILES):
            return "ode"
        return "emblem" + token[len("crest"):]
    if token == "Crest":
        # A C# member named Crest is the emblem; in Swift and prose the
        # bare word is the product or its module.
        return "Emblem" if path.suffix == ".cs" and kind == "code" else "Ode"
    if re.match(r"crest[A-Z0-9]", token):
        token = "ode" + token[len("crest"):]
    for prefix in EMBLEM_PREFIXES:
        if prefix in token:
            return token.replace(prefix, prefix.replace("Crest", "Emblem"))
    stems = "|".join(EMBLEM_STEMS)
    token = re.sub(r"Crest(?=(?:" + stems + r")(?:[A-Z0-9_]|$|s\b))", "Emblem", token)
    return product_token(token)


def map_identifiers(text, path, kind):
    return IDENTIFIER.sub(lambda match: map_token(match.group(0), path, kind), text)


def mask(text):
    """`text` with protected spans replaced by placeholders, and the spans."""
    spans = []

    def hide(match):
        spans.append(match.group(0))
        return f"\x00{len(spans) - 1}\x00"

    for pattern in PROTECTED:
        text = pattern.sub(hide, text)
    return text, spans


def unmask(text, spans):
    return re.sub(r"\x00(\d+)\x00", lambda match: spans[int(match.group(1))], text)


def map_prose(text, path, emblem_words=True):
    """Comments, docs and scripts: identifiers, product words and lower-case
    names in paths."""
    for old, new in sorted(LOWER_SUBSTRINGS.items(), key=lambda item: -len(item[0])):
        text = text.replace(old, new)
    text = re.sub(r"\b([Aa]) (?=Crest\b(?![-/]))", lambda m: "An " if m.group(1) == "A" else "an ", text)
    if emblem_words:
        text = re.sub(r"\b([Aa]) (?=crest\b(?![\w\-:/]|\.\w))", lambda m: "An " if m.group(1) == "A" else "an ", text)
    # Lower-case "crest" is the emblem only as a word of prose in comments
    # and documents; scripts and data use it as the product's name.
    if emblem_words:
        text = re.sub(r"(?<![\w/.\-@`:])crest(s?)(?![\w\-:/]|\.\w)", r"emblem\1", text)
    return IDENTIFIER.sub(lambda match: map_token(match.group(0), path, "prose")
                          if match.group(0) not in ("crest", "crests") else match.group(0), text)


def map_string(text, path):
    if str(path).endswith(UNTOUCHED_STRING_FILES):
        return text
    if str(path).endswith(CODE_TEMPLATE_FILES):
        return map_identifiers(text, path, "template")
    for pattern, replacement in STRING_RULES:
        text = pattern.sub(replacement, text)
    return text


# MARK: - Lexing


def lex(text, language):
    """Splits source text into (kind, chunk) pieces: code, comment, string.
    Interpolated expressions inside strings are lexed as code."""
    pieces = []
    length = len(text)

    def comment_end(position):
        if text.startswith("//", position):
            newline = text.find("\n", position)
            return length if newline < 0 else newline
        depth = 0
        cursor = position
        while cursor < length:
            if text.startswith("/*", cursor):
                depth += 1
                cursor += 2
                continue
            if text.startswith("*/", cursor):
                depth -= 1
                cursor += 2
                if depth == 0 or language != "swift":
                    return cursor
                continue
            cursor += 1
        return length

    def string_opening(position):
        """(opening length, closing delimiter, interpolation opener, escapes)
        for a string literal starting at `position`, or None."""
        rest = text[position:position + 12]
        if language == "swift":
            match = re.match(r'(#*)("""|")', rest)
            if not match or (not match.group(1) and text[position] != '"'):
                return None
            hashes = match.group(1)
            return len(match.group(0)), match.group(2) + hashes, "\\" + hashes + "(", not hashes, match.group(2) == '"'
        if language == "cs":
            match = re.match(r'(\$*)(@?)(\$*)("{3,}|")', rest)
            if not match:
                return None
            if position > 0 and (text[position - 1].isalnum() or text[position - 1] == "_") and match.group(0)[0] != '"':
                return None
            dollars = len(match.group(1)) + len(match.group(3))
            verbatim = bool(match.group(2))
            quote = match.group(4)
            opener = "{" * dollars if dollars else None
            return len(match.group(0)), quote, opener, not verbatim and quote == '"', quote == '"' and not verbatim
        if text[position] == '"':
            return 1, '"', None, True, True
        return None

    def string_spans(position):
        """The end of the string at `position` and its interpolations as
        (start, end) spans of code."""
        opening, close, opener, escapes, single_line = string_opening(position)
        cursor = position + opening
        spans = []
        while cursor < length:
            if text.startswith(close, cursor):
                if language == "cs" and close == '"' and not escapes and text.startswith('""', cursor):
                    cursor += 2
                    continue
                return cursor + len(close), spans
            if opener and text.startswith(opener, cursor):
                if language == "cs" and len(opener) == 1 and text.startswith("{{", cursor):
                    cursor += 2
                    continue
                code_start = cursor + len(opener)
                code_end = matching_close(code_start, "(" if language == "swift" else "{",
                                          ")" if language == "swift" else "}")
                spans.append((code_start, code_end))
                cursor = code_end + 1
                continue
            if escapes and text[cursor] == "\\":
                cursor += 2
                continue
            if single_line and text[cursor] == "\n":
                return cursor, spans
            cursor += 1
        return length, spans

    def matching_close(position, opener, closer):
        """The index of the bracket closing an interpolation that starts at `position`."""
        depth = 1
        cursor = position
        while cursor < length:
            if text.startswith("//", cursor) or text.startswith("/*", cursor):
                cursor = comment_end(cursor)
                continue
            if string_opening(cursor):
                cursor = string_spans(cursor)[0]
                continue
            character = text[cursor]
            if character == opener:
                depth += 1
            elif character == closer:
                depth -= 1
                if depth == 0:
                    return cursor
            cursor += 1
        return length

    def char_literal(position):
        if language not in ("cs", "c") or text[position] != "'":
            return None
        match = re.match(r"'(?:\\.|[^'\\\n])+'", text[position:position + 12])
        return len(match.group(0)) if match else None

    index = 0
    start = 0
    while index < length:
        if text.startswith("//", index) or text.startswith("/*", index):
            if index > start:
                pieces.append(("code", text[start:index]))
            end = comment_end(index)
            pieces.append(("comment", text[index:end]))
            index = start = end
            continue
        literal = char_literal(index)
        if literal:
            if index > start:
                pieces.append(("code", text[start:index]))
            pieces.append(("string", text[index:index + literal]))
            index = start = index + literal
            continue
        if text[index] in '"#$@' and string_opening(index):
            if index > start:
                pieces.append(("code", text[start:index]))
            end, spans = string_spans(index)
            cursor = index
            for span_start, span_end in spans:
                pieces.append(("string", text[cursor:span_start]))
                pieces.extend(lex(text[span_start:span_end], language))
                cursor = span_end
            pieces.append(("string", text[cursor:end]))
            index = start = end
            continue
        index += 1
    if length > start:
        pieces.append(("code", text[start:length]))
    return pieces


